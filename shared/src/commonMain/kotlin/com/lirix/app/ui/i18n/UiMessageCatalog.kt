    fun text(source: String, language: InterfaceLanguage, vararg arguments: Any?): String {
        val template = if (language == InterfaceLanguage.EN) english[source] ?: source else source
        return Regex("\\{([0-9]+)\\}").replace(template) { match ->
            arguments.getOrNull(match.groupValues[1].toInt())?.toString() ?: match.value
        }.replace("\\n", "\n")
    }
