    private val httpStatus = Regex("\\(HTTP (\\d{3})\\)$")

    fun text(source: String, language: InterfaceLanguage, vararg arguments: Any?): String {
        if (language == InterfaceLanguage.EN && source !in english) {
            // Source errors that carry an HTTP status are built by the providers; translate the pattern.
            httpStatus.find(source)?.let { match ->
                english[source.removeSuffix(match.value) + "(HTTP {0})"]?.let { return it.replace("{0}", match.groupValues[1]) }
            }
        }
        val template = if (language == InterfaceLanguage.EN) english[source] ?: source else source
        return Regex("\\{([0-9]+)\\}").replace(template) { match ->
            arguments.getOrNull(match.groupValues[1].toInt())?.toString() ?: match.value
        }.replace("\\n", "\n")
    }
